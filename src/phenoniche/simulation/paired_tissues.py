"""Controlled healthy/cancer tissue pairs; expression injection precedes CCC.

Synthetic disease mechanisms and type roles are assumptions, not biological
annotations. Reuse scCube-derived type means, never old cells or old CCC.
"""
from dataclasses import dataclass, asdict
from pathlib import Path
import json
import anndata as ad
import numpy as np
import pandas as pd
from scipy.special import expit
from ..storage import STORAGE_ROOT
from .response_simulation import checksum

TYPES = ('Epithelial','Fibroblast','Macrophage','T cell','Endothelial')
NICHES = ('Epithelial compartment','Stromal compartment','Immune pocket',
          'Homeostatic interface','Disease interface A','Disease interface B')
PROGRAMS = (
    ('Epithelial homeostasis',0,0),('Stromal support',1,0),
    ('Immune communication',2,3),('Homeostatic interface',0,1),
    ('Vascular support',4,1),('Disease interface A',0,1),
    ('Disease interface B',0,1),('Disease immune response',2,3))


@dataclass(frozen=True)
class PairedConfig:
    output_dir: str = str(STORAGE_ROOT/'outputs/healthy_cancer_communication')
    background_dir: str = str(STORAGE_ROOT/'outputs/tumor_edge_gene_rich_core_exterior_active_simulation')
    pairs: int = 4
    cells_per_slice: int = 2000
    radius_um: float = 300.
    seed: int = 52173
    disease_strength: float = 3.5
    shared_strength: float = 3.0
    dispersion: float = 15.
    sample_noise: float = .08
    epochs: int = 40
    patience: int = 6
    batch_size: int = 128
    hidden: int = 64
    nmf_iterations: int = 500
    k_min: int = 4
    k_max: int = 15
    device: str = 'cuda:2'
    figure_dpi: int = 300
    extra_training_pairs: int = 0
    diverse_training_geometry: bool = False
    encoder_gene_selection: str = 'all'
    reuse_tissue_dir: str = ''
    prefix_reference_dir: str = ''
    training_centers_per_slice: int = 0

    def __post_init__(self):
        if self.pairs<4 or self.cells_per_slice<100 or self.radius_um<=0:
            raise ValueError('Need >=4 independent pairs and >=100 cells/slice')
        if self.disease_strength<0 or self.shared_strength<=0 or self.dispersion<=0 or self.sample_noise<0:
            raise ValueError('Invalid signal/noise parameters')
        if self.epochs<2 or self.patience<2 or not 4<=self.k_min<=self.k_max<=15:
            raise ValueError('Invalid training or K-selection budget')
        if self.device.startswith('cuda:') and self.device!='cuda:2':
            raise ValueError('This experiment is restricted to GPU 2')
        if self.extra_training_pairs<0 or self.encoder_gene_selection not in ('all','lr_markers'):
            raise ValueError('Invalid extra training count or gene selection')
        if self.reuse_tissue_dir and self.extra_training_pairs:
            raise ValueError('Reused data and newly generated training slices are separate controls')
        if not 0<=self.training_centers_per_slice<=self.cells_per_slice:
            raise ValueError('Training-center budget exceeds slice size')

    def to_dict(self):return asdict(self)

    @classmethod
    def from_json(cls,path):return cls(**json.loads(Path(path).read_text()))


def background(config):
    source=Path(config.background_dir)
    a=ad.read_h5ad(source/'before_injection.h5ad')
    lr=pd.read_csv(source/'lr.csv').iloc[:75][['lr_id','ligand','receptor','source']].copy()
    if len(lr)!=75 or len(set(lr.ligand)|set(lr.receptor))!=150:
        raise ValueError('Expected the audited 75 disjoint real LR pairs')
    # The fifth expression scaffold is synthetic, relabelled as Endothelial.
    # It is not a claim that this scaffold recapitulates endothelial biology.
    donor_types=('Normal epithelial','Fibroblast','Macrophage','T cell','Tumor')
    x=np.asarray(a.X,np.float32)
    means=np.stack([x[a.obs.cell_type.to_numpy()==t].mean(0) for t in donor_types])
    return tuple(a.var_names),means,lr


def spatial_design(config,pair):
    rng=np.random.default_rng(config.seed+1009*pair)
    n=config.cells_per_slice;theta=rng.uniform(-np.pi,np.pi,n)
    r=config.radius_um*np.sqrt(rng.uniform(0,1,n));phase=rng.uniform(-.5,.5)
    xy=np.column_stack((r*np.cos(theta),r*np.sin(theta))).astype(np.float32)
    core_fraction=.45;inner_fraction=.43;outer_fraction=.68
    warp_a=.07;warp_b=.04;immune_phase=phase;state_phase=phase
    if config.diverse_training_geometry and pair>=config.pairs:
        # Extra pairs vary tissue geometry and rotate molecular patches; the
        # old validation/test pairs are generated by the unchanged branch.
        phase=rng.uniform(-np.pi,np.pi);immune_phase=rng.uniform(-np.pi,np.pi)
        state_phase=rng.uniform(-np.pi,np.pi)
        core_fraction=rng.uniform(.39,.50);inner_fraction=core_fraction-.02
        outer_fraction=core_fraction+rng.uniform(.19,.25)
        warp_a=rng.uniform(.035,.11);warp_b=rng.uniform(.015,.07)
    rho=r*(1+warp_a*np.sin(3*theta+phase)+warp_b*np.cos(5*theta-phase))
    core=expit((core_fraction*config.radius_um-rho)/9)
    ring=expit((rho-inner_fraction*config.radius_um)/8)*expit((outer_fraction*config.radius_um-rho)/8)
    # Immune pockets and interfacial satellites are not condition-specific.
    immune=expit((np.sin(2.6*xy[:,0]/config.radius_um+immune_phase)+np.cos(4.2*xy[:,1]/config.radius_um)-1.1)*7)
    immune*=expit((rho-outer_fraction*config.radius_um)/10)
    region=np.ones(n,int);region[core>.5]=0;region[ring>.5]=3;region[immune>.45]=2
    fractions=np.array([[.72,.12,.06,.06,.04],[.18,.44,.14,.14,.10],
                        [.15,.18,.30,.29,.08],[.35,.30,.15,.15,.05]])
    # Draw types once per pair: exact composition/position match across condition.
    types=np.array([rng.choice(5,p=fractions[j]) for j in region])
    wave=np.sin(2*theta+phase)+.35*np.sin(5*theta-phase)
    gate_a=expit((wave-.2)*7)*ring
    gate_b=expit((-wave-.2)*7)*ring
    # Multiple irregular patches; 20–30% of interface stays shared.
    amplitude=rng.lognormal(0,.15,n).astype(np.float32)
    state=np.column_stack((np.sin(3*xy[:,0]/config.radius_um+state_phase),
                           np.cos(3*xy[:,1]/config.radius_um-state_phase)))
    return xy,types,region,core,ring,immune,gate_a,gate_b,amplitude,state


def simulate(config,genes,means,lr):
    """Generate independent counts from matched latent tissues, not CCC labels."""
    gene_index={g:i for i,g in enumerate(genes)}
    lr_genes=np.array([gene_index[g] for g in [*lr.ligand,*lr.receptor]])
    if len(genes)<150:raise ValueError('Gene panel is missing LR genes')
    rng=np.random.default_rng(config.seed+834)
    state_loadings=rng.normal(0,.12,(2,len(genes)))
    state_loadings[:,lr_genes]=0
    records=[];blocks=[];activities=[];before_blocks=[];program_records=[]
    links=lr.copy();links['program_id']=np.repeat(np.arange(8),6).tolist()+[-1]*27
    links['sender']='';links['receiver']='';links['loading']=0.
    for p,(name,s,r) in enumerate(PROGRAMS):
        keep=links.program_id==p;links.loc[keep,['sender','receiver','loading']]=[TYPES[s],TYPES[r],1/6]
        program_records.append({'program_id':p,'name':name,'sender':TYPES[s],'receiver':TYPES[r],
                                'scope':'disease' if p>=5 else 'shared','role_evidence':'synthetic design; LR identities from public atlas'})
    for pair in range(config.pairs+config.extra_training_pairs):
        xy,types,region,core,ring,immune,ga,gb,amp,state=spatial_design(config,pair)
        # Baseline rates and nuisance states are condition independent.
        rate=np.maximum(means[types],.02)*np.exp(state@state_loadings)
        rate[:,lr_genes]=.06
        shared=np.column_stack((.15+.85*core,.25+.75*(1-core)*(1-immune),
                                 .18+.82*immune,ring,np.full(len(types),.35),
                                 np.zeros((len(types),3)))).astype(np.float32)
        for condition in ('Healthy','Cancer'):
            sample=f'pair{pair+1}_{condition.lower()}'
            draw=np.random.default_rng(config.seed+pair*10007+(1 if condition=='Healthy' else 2))
            activity=shared.copy();truth=region.copy()
            if condition=='Cancer' and config.disease_strength>0:
                activity[:,5]=ga;activity[:,6]=gb;activity[:,7]=.6*ga+.85*gb
                activity[:,3]*=1-.8*np.maximum(ga,gb)
                truth[(region==3)&(ga>.45)]=4;truth[(region==3)&(gb>.45)]=5
            activity*=amp[:,None]
            # Positive independent slice effects are unrelated to condition;
            # no global cancer expression shift or condition-specific marker.
            nuisance=draw.normal(0,config.sample_noise,len(genes));nuisance[lr_genes]=0
            baseline=rate*np.exp(nuisance)[None,:]
            injected=baseline.copy()
            for p,(_,sender,receiver) in enumerate(PROGRAMS):
                group=links[links.program_id==p]
                strength=config.disease_strength if p>=5 else config.shared_strength
                for row in group.itertuples():
                    li=gene_index[row.ligand];ri=gene_index[row.receptor]
                    injected[types==sender,li]+=.22+strength*activity[types==sender,p]
                    injected[types==receiver,ri]+=.22+strength*activity[types==receiver,p]
            # Remaining public LR pairs provide structured background CCC.
            for j,row in enumerate(links[links.program_id<0].itertuples()):
                injected[types==j%5,gene_index[row.ligand]]+=.6
                injected[types==(j+1)%5,gene_index[row.receptor]]+=.6
            library=draw.lognormal(-.5*.2**2,.2,len(types))
            injected*=library[:,None];baseline*=library[:,None]
            # Shared Gamma rate fluctuations for before/after audit; independent
            # count draws ensure effects are rates, never count multiplication.
            gamma=draw.gamma(config.dispersion,1/config.dispersion,injected.shape)
            counts=draw.poisson(injected*gamma).astype(np.float32)
            before=draw.poisson(baseline*gamma).astype(np.float32)
            non_lr=np.ones(len(genes),bool);non_lr[lr_genes]=False
            before[:,non_lr]=counts[:,non_lr]
            # Pair membership determines folds; neither condition nor truth is
            # consulted by model fitting or unsupervised K selection.
            fold=0 if pair<config.pairs-2 or pair>=config.pairs else 1 if pair==config.pairs-2 else 2
            for i in range(len(types)):
                records.append({'cell_id':f'{sample}_{i}','sample_id':sample,'pair_id':pair,
                                'condition':condition,'cell_type':TYPES[types[i]],'true_niche':int(truth[i]),
                                'fold':fold,'local_x':float(xy[i,0]),'local_y':float(xy[i,1])})
            blocks.append(counts);before_blocks.append(before);activities.append(activity)
    obs=pd.DataFrame(records);obs.index=obs.cell_id
    a=ad.AnnData(np.concatenate(blocks),obs=obs,var=pd.DataFrame(index=genes))
    a.obsm['spatial']=obs[['local_x','local_y']].to_numpy(np.float32)
    a.obsm['true_program_activity']=np.concatenate(activities)
    a.layers['before_injection']=np.concatenate(before_blocks)
    a.uns['simulation_scope']='Controlled communication-state change, not a complete cancer model; same epithelial type in both conditions'
    return a,links,pd.DataFrame(program_records)


def generate(config):
    out=Path(config.output_dir)
    permitted=any(out.resolve()!=root.resolve() and out.resolve().is_relative_to(root.resolve())
                  for root in (STORAGE_ROOT/'outputs',STORAGE_ROOT/'tmp'))
    if out.is_symlink() or not permitted:
        raise ValueError('Direct NAS outputs path required')
    out.mkdir(parents=True,exist_ok=True)
    source=Path(config.background_dir)
    manifest={'config':config.to_dict(),'implementation':checksum(__file__),
              'source':{f:checksum(source/f) for f in ('before_injection.h5ad','lr.csv')}}
    if config.reuse_tissue_dir:
        reused=Path(config.reuse_tissue_dir)
        manifest['reused_data']={f:checksum(reused/f) for f in ('tissues.h5ad','lr.csv','ground_truth/programs.csv')}
    if config.prefix_reference_dir:
        manifest['prefix_data']=checksum(Path(config.prefix_reference_dir)/'tissues.h5ad')
    marker=out/'data_complete.json'
    if marker.exists():
        old=json.loads(marker.read_text())
        if old['manifest']!=manifest:raise ValueError('Completed paired simulation differs; refusing to overwrite')
        if not all(checksum(out/f)==h for f,h in old['files'].items()):raise ValueError('Simulation cache corrupted')
        return out
    if config.reuse_tissue_dir:
        reused=Path(config.reuse_tissue_dir);a=ad.read_h5ad(reused/'tissues.h5ad');lr=pd.read_csv(reused/'lr.csv')
        programs=pd.read_csv(reused/'ground_truth/programs.csv')
    else:
        genes,means,lr=background(config);a,lr,programs=simulate(config,genes,means,lr)
    if config.prefix_reference_dir:
        old=ad.read_h5ad(Path(config.prefix_reference_dir)/'tissues.h5ad')
        n=len(old)
        if not (np.array_equal(a.X[:n],old.X) and np.array_equal(a.obs.cell_id.iloc[:n],old.obs.cell_id)
                and np.array_equal(a.obsm['spatial'][:n],old.obsm['spatial'])
                and np.array_equal(a.obs.fold.iloc[:n],old.obs.fold)):
            raise AssertionError('Original slices changed while adding independent training pairs')
    a.write_h5ad(out/'tissues.h5ad',compression='gzip');lr.to_csv(out/'lr.csv',index=False)
    gt=out/'ground_truth';gt.mkdir(exist_ok=True)
    programs.to_csv(gt/'programs.csv',index=False);a.obs.to_csv(gt/'cells.csv.gz',index=False)
    np.save(gt/'cell_program_activity.npy',a.obsm['true_program_activity'])
    audit={'source':('Exact reused tissue data for input-only control' if config.reuse_tissue_dir else
                     'Existing scCube-derived type means; fresh Gamma–Poisson draws; original slice prefix preserved for fixed holdout'),
           'n_cells':len(a),'n_slices':int(a.obs.sample_id.nunique()),'n_genes':a.n_vars,'LR_pairs':len(lr),
           'cell_types':list(TYPES),'programs':8,'niche_states':6,'knn':30,'sigma_um':20,
           'composition':'Exact type/coordinate matching within each independently generated pair',
           'disease_effect':'Only LR gene expression rates; no direct CCC injection',
           'synthetic_type_scaffold':'Endothelial uses a synthetic expression scaffold inherited from the fifth donor type; not a validated biological annotation',
           'truth_used_for_training':False,'disease_supervision':False,'population_inference':False}
    (out/'data_audit.json').write_text(json.dumps(audit,indent=2)+'\n')
    files=('tissues.h5ad','lr.csv','ground_truth/programs.csv','ground_truth/cell_program_activity.npy','data_audit.json')
    marker.write_text(json.dumps({'manifest':manifest,'files':{f:checksum(out/f) for f in files}},indent=2)+'\n')
    return out
